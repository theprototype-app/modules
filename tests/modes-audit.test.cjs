const cell = (v, note = '') => ({ v, note });

async function setMode(page, mode) {
	await page.evaluate((m) => {
		const s = window.__stores;
		s.isLocked.set(false);
		s.objectActions.deselectObject();
		s.objectActions.setEditorMode(m);
	}, mode);
	// outside the click-cycle window (a repeat on one pixel within 1.5 s walks DOWN)
	await page.waitForTimeout(1700);
}

async function checkList(page, items) {
	await page.evaluate(() => {
		window.__stores.objectListClose.set(false);
		window.__stores.inspectorClose?.set(true);
	});
	await page.waitForTimeout(1200);
	const notes = [];
	let ok = true;
	for (const item of items) {
		if (item.uuid) {
			let found = await page.evaluate((id) => !!document.querySelector('#object-tree')?.querySelector('[id="' + id + '"]'), item.uuid);
			if (!found) {
				// a long tree is virtualised: ask the list's own search for it
				const name = await page.evaluate((id) => window.__audit.objects().getObjectByProperty('uuid', id)?.name ?? '', item.uuid);
				const search = page.locator('#object-search');
				if ((await search.count()) && name) {
					await search.fill(name);
					await page.waitForTimeout(500);
					found = await page.evaluate((id) => !!document.querySelector('#object-tree')?.querySelector('[id="' + id + '"]'), item.uuid);
					await search.fill('');
				}
			}
			if (!found) {
				ok = false;
				notes.push(item.label + ' not in the tree');
			}
		} else {
			const row = page.locator(`#module-content .module-content-row[data-group="${item.group}"]`);
			if ((await row.count()) !== 1) {
				ok = false;
				notes.push(item.group + ': no Module content row');
				continue;
			}
			const label = ((await row.locator('.module-content-name').textContent()) ?? '').trim();
			if (item.listLabel && label !== item.listLabel) {
				ok = false;
				notes.push(`label "${label}" (want "${item.listLabel}")`);
			} else notes.push(`"${label}"`);
			if (item.children) {
				const expander = row.locator('button[aria-label="Show children"]');
				if (await expander.count()) {
					await expander.click();
					await page.waitForTimeout(300);
				}
				const kids = await row.locator('.module-content-child').count();
				if (!kids) {
					ok = false;
					notes.push('no named parts listed');
				} else notes.push(kids + ' parts');
			}
		}
	}
	await page.evaluate(() => window.__stores.objectListClose.set(true));
	await page.waitForTimeout(500);
	return cell(ok ? 'PASS' : 'FAIL', notes.join('; '));
}

/** frame the target and find a clean pixel; a covered one (a HUD card over the middle)
 * retries with the target slid across the view */
async function frameAndAim(page, target, from) {
	let aim = null;
	for (const shift of [[0, 0], [0.45, 0], [-0.45, 0], [0, 0.3], [0.45, 0.3]]) {
		await lib(page, 'frame', target, { from, shift });
		await page.waitForTimeout(700);
		aim = await lib(page, 'aim', target);
		if (aim.ok || !/covered/.test(aim.why ?? '')) return aim;
	}
	return aim;
}

async function clickSelects(page, item) {
	await setMode(page, 'edit');
	const aim = await frameAndAim(page, item, item.from);
	if (!aim.ok) return { ok: false, note: item.label + ': no clean pixel (' + aim.why + ')' };
	await page.mouse.click(aim.x, aim.y);
	await page.waitForTimeout(600);
	if (item.uuid) {
		const sel = await lib(page, 'selection');
		return { ok: sel.includes(item.uuid), note: item.label + (sel.includes(item.uuid) ? '' : ' -> selection ' + JSON.stringify(sel.slice(0, 2)) + ' / proxy ' + (await lib(page, 'moduleSelection'))) };
	}
	const proxy = await lib(page, 'moduleSelection');
	return { ok: proxy === item.group, note: item.label + (proxy === item.group ? ' (proxy)' : ' -> proxy ' + proxy + ', selection ' + JSON.stringify(await lib(page, 'selection'))) };
}

async function checkSelect(page, items) {
	const notes = [];
	let ok = true;
	let any = false;
	for (const item of items) {
		if (item.noSelect) {
			notes.push(item.label + ': N-A — ' + item.noSelect);
			continue;
		}
		any = true;
		const r = await clickSelects(page, item);
		ok = ok && r.ok;
		if (!r.ok || r.note.includes('proxy')) notes.push(r.note);
	}
	if (!any) return cell('N-A', notes.join('; '));
	return cell(ok ? 'PASS' : 'FAIL', notes.join('; '));
}

async function gizmoDrag(page, item) {
	await setMode(page, 'edit');
	await page.evaluate((uuid) => {
		window.__stores.transformMode.set('translate');
		window.__stores.objectActions.selectObject(uuid);
	}, item.uuid);
	await lib(page, 'frame', item, { from: [0.35, 0.8, 1.4], dist: 3.2 });
	await page.waitForTimeout(900);
	const attached = await lib(page, 'gizmoObject');
	if (attached !== item.uuid) return { ok: false, note: item.label + ': no gizmo on it' };
	// the X arrow, else Y or Z (a game's HUD may sit over one of them in the editor)
	let handle = null;
	for (const axis of ['X', 'Z', 'Y']) {
		handle = await lib(page, 'gizmoHandle', axis);
		if (handle?.onCanvas) break;
	}
	if (!handle || !handle.onCanvas) return { ok: false, note: item.label + ': no gizmo handle on the canvas (covered)' };
	const before = await lib(page, 'position', item.uuid);
	await page.mouse.move(handle.x, handle.y);
	await page.waitForTimeout(100);
	await page.mouse.down();
	for (let i = 1; i <= 8; i++) await page.mouse.move(handle.x + handle.dx * i * 10, handle.y + handle.dy * i * 10, { steps: 2 });
	await page.mouse.up();
	await page.waitForTimeout(500);
	const after = await lib(page, 'position', item.uuid);
	const moved = before && after ? Math.hypot(...after.map((v, i) => v - before[i])) : 0;
	return { ok: moved > 0.05, note: item.label + ' moved ' + moved.toFixed(2) + ' m' };
}

async function checkMove(page, items) {
	const notes = [];
	let ok = true;
	let any = false;
	for (const item of items) {
		if (item.uuid) {
			any = true;
			const r = await gizmoDrag(page, item);
			ok = ok && r.ok;
			notes.push(r.note);
		} else {
			if (item.noSelect) {
				notes.push(item.label + ': N-A (not selectable)');
				continue;
			}
			// scene-root content is regenerated by its module: READ-ONLY, through its proxy
			any = true;
			await setMode(page, 'edit');
			const selected = await page.evaluate((g) => {
				window.__stores.objectActions.selectModuleGroup?.(g);
				return window.__stores.moduleSDK.moduleContentDebug().selection?.name ?? null;
			}, item.group);
			// the object list is the documented way: its row click selects the proxy
			let proxy = selected;
			if (proxy !== item.group) {
				await page.evaluate(() => window.__stores.objectListClose.set(false));
				await page.waitForTimeout(900);
				const row = page.locator(`#module-content .module-content-row[data-group="${item.group}"] .module-content-name`);
				if (await row.count()) await row.click();
				await page.waitForTimeout(600);
				proxy = await lib(page, 'moduleSelection');
				await page.evaluate(() => window.__stores.objectListClose.set(true));
			}
			const gizmo = await lib(page, 'gizmoObject');
			const sel = await lib(page, 'selection');
			const inObjects = await page.evaluate((g) => !!window.__audit.objects().getObjectByName(g), item.group);
			const readOnly = proxy === item.group && !gizmo && sel.length === 0 && !inObjects;
			ok = ok && readOnly;
			notes.push(item.label + (readOnly ? ': read-only (proxy, no gizmo)' : `: proxy ${proxy}, gizmo ${gizmo}, selection ${sel.length}, in objectsGroup ${inObjects}`));
		}
	}
	if (!any) return cell('N-A', notes.join('; '));
	return cell(ok ? 'PASS' : 'FAIL', notes.join('; '));
}

/** read an effect; the default is the generic reaction */
async function effectOf(page, spec) {
	if (spec.effect) return spec.effect(page);
	return lib(page, 'reaction');
}
const changed = (a, b) => JSON.stringify(a) !== JSON.stringify(b);

async function clickEffect(page, mode, spec) {
	await setMode(page, mode);
	const aim = await frameAndAim(page, spec.target, spec.target.from);
	if (!aim.ok) return { ok: null, note: 'no clean pixel (' + aim.why + ')' };
	await page.evaluate(() => window.__stores.toastStore.set([]));
	const mark = await page.evaluate(() => window.__auditSent.length);
	const before = await effectOf(page, spec);
	await page.mouse.click(aim.x, aim.y);
	await page.waitForTimeout(900);
	const after = await effectOf(page, spec);
	const types = await page.evaluate((m) => window.__auditSent.slice(m).map((x) => x.type + (x.op ? ':' + x.op : '')).join(','), mark);
	const sel = await lib(page, 'selection');
	const proxy = await lib(page, 'moduleSelection');
	return { ok: changed(before, after), selected: sel.length > 0 || !!proxy, note: JSON.stringify(before) + ' -> ' + JSON.stringify(after) + ` (hit ${aim.first}; sent ${types || 'nothing'})` };
}

async function checkEditQuiet(page, spec) {
	if (spec.editQuiet?.na) return cell('N-A', spec.editQuiet.na);
	if (!spec.interact?.target) return cell('N-A', spec.interact?.na ?? 'no interactive part');
	const r = await clickEffect(page, 'edit', spec.interact);
	if (r.ok === null) return cell('FAIL', r.note);
	const quiet = !r.ok && r.selected;
	return cell(quiet ? 'PASS' : 'FAIL', (r.ok ? 'INTERACTED in Edit: ' : '') + (r.selected ? '' : 'selected nothing; ') + r.note);
}

async function checkInteract(page, spec) {
	const i = spec.interact;
	if (!i || i.na) return cell('N-A', i?.na ?? 'no interactive part');
	if (i.saber) return saberCheck(page, 'interact');
	const r = await clickEffect(page, 'interact', i);
	if (r.ok === null) return cell('FAIL', r.note);
	const ok = r.ok && !r.selected;
	return cell(ok ? 'PASS' : 'FAIL', (r.selected ? 'ALSO SELECTED; ' : '') + r.note);
}

async function tap(page) {
	await page.evaluate(
		() =>
			new Promise((resolve) => {
				window.dispatchEvent(new PointerEvent('pointerdown', { button: 0, bubbles: true }));
				setTimeout(() => {
					window.dispatchEvent(new PointerEvent('pointerup', { button: 0, bubbles: true }));
					resolve(true);
				}, 120);
			})
	);
}

async function checkPlay(page, spec) {
	const p = spec.play ?? spec.interact;
	if (!p || p.na) return cell('N-A', p?.na ?? 'no interactive part');
	if (p.saber) return saberCheck(page, 'play');
	await setMode(page, 'edit');
	await page.evaluate(() => window.__stores.isLocked.set(true));
	await page.waitForTimeout(800);
	// a game whose Start screen is up in play holds the pointer for its menu (21-E3's
	// substate) — press Start the way its button does: the game state goes to playing
	const started = await page.evaluate(() => {
		let free;
		window.__stores.playPointerFree.subscribe((v) => (free = v))();
		if (free) window.__stores.gameState.setGameState('playing');
		return free;
	});
	if (started) await page.waitForTimeout(800);
	const target = p.playTarget ?? p.target;
	await lib(page, 'aimRig', target, 1.6);
	await page.waitForTimeout(500);
	let aim = await lib(page, 'centreAim', target);
	if (!aim.ok) {
		await lib(page, 'placeCentre', target, 1.6);
		await page.waitForTimeout(500);
		aim = await lib(page, 'centreAim', target);
	}
	if (!aim.ok) {
		await page.evaluate(() => window.__stores.isLocked.set(false));
		return cell('FAIL', 'the crosshair is not on it (' + aim.first + ' @ ' + aim.distance + ')');
	}
	await page.evaluate(() => window.__stores.toastStore.set([]));
	const before = await effectOf(page, p);
	await tap(page);
	await page.waitForTimeout(900);
	const after = await effectOf(page, p);
	const debug = await lib(page, 'playDebug');
	await page.evaluate(() => window.__stores.isLocked.set(false));
	await page.waitForTimeout(400);
	return cell(changed(before, after) ? 'PASS' : 'FAIL', JSON.stringify(before) + ' -> ' + JSON.stringify(after) + ' (crosshair on ' + aim.first + (started ? '; Start pressed' : '') + '; play ' + JSON.stringify(debug) + ')');
}

/** Sabers: the blade must reach an object under the pointer (Interact: the mouse ray;
 * Play: the crosshair ray, 30 P4) and spark a hit */
async function saberCheck(page, mode) {
	await setMode(page, 'edit');
	if (mode === 'interact') await page.evaluate(() => window.__stores.objectActions.setEditorMode('interact'));
	if (mode === 'play') {
		await page.evaluate(() => window.__stores.isLocked.set(true));
		await page.waitForTimeout(800);
	}
	const box = await create(page, '/create box');
	// one metre down the ray through the view's centre: inside the blade (0.55 .. 1.75 m)
	await page.evaluate((uuid) => {
		const s = window.__stores;
		let camera;
		s.globalCamera.subscribe((v) => (camera = v))();
		const at = camera.getWorldPosition(new s.THREE.Vector3()).addScaledVector(camera.getWorldDirection(new s.THREE.Vector3()), 1.1);
		let g;
		s.objectsGroup.subscribe((v) => (g = v))();
		const o = g.getObjectByProperty('uuid', uuid);
		o.position.copy(at);
		o.scale.setScalar(0.5);
		o.updateMatrixWorld(true);
		s.objectsGroup.update((v) => v);
	}, box);
	const before = await sentOp('hit')(page);
	for (let i = 0; i < 6; i++) {
		await page.mouse.move(VIEW.width / 2 + (i % 2), VIEW.height / 2 + (i % 3));
		await page.waitForTimeout(150);
	}
	await page.waitForTimeout(600);
	const after = await sentOp('hit')(page);
	if (mode === 'play') await page.evaluate(() => window.__stores.isLocked.set(false));
	await page.evaluate((uuid) => window.__stores.commandsHandler.sceneCommand('/clear ' + uuid), box);
	return cell(after > before ? 'PASS' : 'FAIL', 'hit sparks ' + before + ' -> ' + after);
}

