// modes-audit — EVERY module under the editor's two modes and Play (roadmap 30, lane
// 30-mod-audit). Core 30 P1-P4 split the editor click into EDIT (a click selects; a module
// click handler runs only if it asked for {modes: ['edit']}) and INTERACT (the play-style
// click), and listed scene-root module content in the object list's "Module content"
// section. This flight measures, per module, what a USER meets:
//
//   list      every object/row the module made appears in the object list — the scene
//             tree for objectsGroup content, the Module content section (with a label a
//             person reads) for scene-root groups
//   select    a REAL click on its projected pixel in EDIT selects it (or its proxy)
//   move      a real gizmo drag moves a replicated object; scene-root content is
//             regenerated by its module, so there it asserts READ-ONLY instead (the proxy
//             is selected, no gizmo, nothing joins the selection set)
//   editQuiet the same EDIT click on the module's interactive part does NOT interact
//   interact  in INTERACT a real click on it does the module's thing (a key sounds, a
//             button presses) and selects nothing
//   play      in PLAY (isLocked, the crosshair tap — play-interact's recipe) it still does
//
// Content is created the way a user does: the module's menu button, its /create
// primitive, its toolbox, or its Games-tab template (read from the scenes checkout,
// SCENES_DIR, never written). Every viewport click lands on a pixel verified FIRST to
// resolve to the intended mesh through the app's own pick, so no cell can pass on a
// click that hit empty space. A cell that cannot apply is N-A with its reason.
//
//   APP_URL=… node tests/modes-audit.test.cjs            every module
//   ONLY=piano,music-lab node tests/modes-audit.test.cjs  a few
//   AUDIT_OUT=/path/report.json                           also write the table as JSON
