function pageLib() {
	const s = window.__stores;
	// NOT 0: core's flyTo divides by its duration, and a 0 ms tween leaves the camera at NaN
	// for a frame (measured: the door-keypad row's listener threw "non-finite AudioParam")
	const FLY_MS = 1;
	const THREE = s.THREE;
	const read = (name) => {
		let v;
		s[name].subscribe((x) => (v = x))();
		return v;
	};
	const objects = () => read('objectsGroup');
	const scene = () => read('globalScene');
	const camera = () => read('globalCamera');
	const canvas = () => read('globalRenderer').domElement;
	const topOf = (node) => {
		const root = objects();
		while (node && node.parent && node.parent !== root) node = node.parent;
		return node?.parent === root ? node : null;
	};
	/** the root a spec names: an objectsGroup uuid, or a scene-root group */
	const rootOf = (spec) =>
		spec.uuid ? objects().getObjectByProperty('uuid', spec.uuid) : spec.group ? scene().getObjectByName(spec.group) : null;
	/** does `mesh` satisfy the spec's part filter? */
	const partOk = (spec, mesh) => {
		if (!mesh) return false;
		if (spec.part) {
			const re = new RegExp(spec.part);
			for (let n = mesh; n; n = n.parent) {
				if (re.test(n.name ?? '')) return true;
				if (n === rootOf(spec)) break;
			}
			return false;
		}
		if (spec.midi != null) return mesh.userData?.midi === spec.midi;
		if (spec.anyMidi) return typeof mesh.userData?.midi === 'number';
		if (spec.userKey) return !!mesh.userData?.[spec.userKey] || !!mesh.parent?.userData?.[spec.userKey];
		return true;
	};
	/** the mesh to aim at: the first visible mesh under the root that satisfies the spec */
	const meshOf = (spec) => {
		const root = rootOf(spec);
		if (!root) return null;
		let found = null;
		root.traverseVisible?.((n) => {
			if (!found && n.isMesh && !n.userData?.isModuleProxy && partOk(spec, n)) found = n;
		});
		return found;
	};
	/** does a hit mesh belong to what the spec aims at? */
	const hitOk = (spec, mesh) => {
		const root = rootOf(spec);
		if (!root || !mesh) return false;
		let inside = false;
		for (let n = mesh; n; n = n.parent) if (n === root) inside = true;
		return inside && partOk(spec, mesh);
	};
	/** every hit the EDITOR pick would consider, nearest first: module groups + the scene */
	// (`extra` = the spec's own scene-root group, so the PIXEL check asks "is this content
	// the nearest thing here" even where the app does not pick it — the click then says
	// what the app does with it)
	const allHits = (ray, extra = null) => {
		const hits = [...s.scenePick.sceneHits(ray, { tinyProxies: true })];
		const names = new Set(s.moduleSDK.moduleInteractiveGroups);
		if (extra) names.add(extra);
		for (const name of names) {
			const root = scene().getObjectByName(name);
			if (root) hits.push(...ray.intersectObject(root, true));
		}
		return hits.filter((hit) => hit.object?.visible !== false).sort((a, b) => a.distance - b.distance);
	};
	/** the hit the editor pick PREFERS: core 30 P2's select-through skips a see-through
	 * shell (effective opacity < 0.25, `userData.pick === 'through'`, a hidden node) in
	 * front of an opaque target, so the pixel check must too */
	const seeThrough = (object) => {
		for (let n = object; n; n = n.parent) {
			if (n.visible === false || n.userData?.pick === 'through') return true;
			if (n === objects() || n === scene()) break;
		}
		const m = Array.isArray(object.material) ? object.material[0] : object.material;
		return !!m && m.transparent && (m.opacity ?? 1) < 0.25;
	};
	const firstHit = (ray, extra) => {
		const hits = allHits(ray, extra);
		return hits.find((hit) => !seeThrough(hit.object)) ?? hits[0] ?? null;
	};
	/** fly the editor camera so the spec's mesh fills a good part of the view */
	const frame = (spec, opts = {}) => {
		const mesh = meshOf(spec);
		if (!mesh) return false;
		mesh.updateWorldMatrix(true, true);
		const box = new THREE.Box3().setFromObject(mesh);
		const centre = box.getCenter(new THREE.Vector3());
		const size = box.getSize(new THREE.Vector3()).length();
		const dist = opts.dist ?? Math.min(4.5, Math.max(1.2, size * 2.2));
		const dir = new THREE.Vector3(...(opts.from ?? [0, 0.9, 1.4])).normalize();
		const at = centre.clone().addScaledVector(dir, dist);
		// `shift` slides the view sideways (fractions of the distance) so the mesh lands
		// off-centre — past a game's HUD card, which sits over the middle in the editor
		const [sx, sy] = opts.shift ?? [0, 0];
		const right = new THREE.Vector3().crossVectors(new THREE.Vector3(0, 1, 0), dir).normalize();
		const up = new THREE.Vector3().crossVectors(dir, right).normalize();
		const slide = right.multiplyScalar(sx * dist).add(up.multiplyScalar(sy * dist));
		s.objectActions.flyTo(at.add(slide).toArray(), centre.clone().add(slide).toArray(), FLY_MS);
		return true;
	};
	/** a pixel over the spec's mesh whose FIRST editor hit is that mesh, on the canvas */
	const aim = (spec) => {
		const mesh = meshOf(spec);
		if (!mesh) return { ok: false, why: 'no mesh' };
		mesh.updateWorldMatrix(true, true);
		const box = new THREE.Box3().setFromObject(mesh);
		const rect = canvas().getBoundingClientRect();
		const cam = camera();
		const ray = new THREE.Raycaster();
		ray.layers.enableAll();
		const candidates = [];
		const c = box.getCenter(new THREE.Vector3());
		candidates.push(c.clone(), new THREE.Vector3(c.x, box.max.y - 0.002, c.z));
		for (const fx of [0.3, 0.5, 0.7])
			for (const fz of [0.3, 0.5, 0.7])
				candidates.push(new THREE.Vector3(box.min.x + (box.max.x - box.min.x) * fx, box.max.y - 0.002, box.min.z + (box.max.z - box.min.z) * fz));
		for (const fy of [0.3, 0.6]) candidates.push(new THREE.Vector3(c.x, box.min.y + (box.max.y - box.min.y) * fy, box.max.z - 0.002));
		let last = null;
		for (const p of candidates) {
			const v = p.clone().project(cam);
			if (Math.abs(v.x) > 0.95 || Math.abs(v.y) > 0.95 || v.z > 1) continue;
			const x = rect.left + ((v.x + 1) / 2) * rect.width;
			const y = rect.top + ((1 - v.y) / 2) * rect.height;
			if (document.elementFromPoint(x, y) !== canvas()) {
				last = 'covered by ' + (document.elementFromPoint(x, y)?.id || document.elementFromPoint(x, y)?.className || '?');
				continue;
			}
			ray.setFromCamera(new THREE.Vector2(v.x, v.y), cam);
			const first = firstHit(ray, spec.group);
			if (first && hitOk(spec, first.object)) return { ok: true, x, y, first: first.object.name || first.object.type };
			last = 'first hit ' + (first ? first.object.name || first.object.type : 'nothing');
		}
		return { ok: false, why: last ?? 'off screen' };
	};
	/** is the spec's mesh the first thing under the CROSSHAIR (play's aim), within reach? */
	const centreAim = (spec) => {
		const ray = new THREE.Raycaster();
		ray.setFromCamera(new THREE.Vector2(0, 0), camera());
		const first = firstHit(ray, spec.group);
		return { ok: !!first && hitOk(spec, first.object) && first.distance <= 6, first: first?.object?.name ?? null, distance: first?.distance ?? null };
	};
	/** frame the mesh dead centre (play aims through the view's centre) */
	const frameCentre = (spec, dist = 1.6) => {
		const mesh = meshOf(spec);
		if (!mesh) return false;
		const box = new THREE.Box3().setFromObject(mesh);
		const centre = box.getCenter(new THREE.Vector3());
		if (spec.top) centre.y = box.max.y - 0.01;
		const dir = new THREE.Vector3(0, 1.1, 1).normalize();
		s.objectActions.flyTo(centre.clone().addScaledVector(dir, dist).toArray(), centre.toArray(), FLY_MS);
		return true;
	};
	/** PLAY aims through the view's centre from the camera play hands it, which the editor
	 * cannot fly (the orbit controls stand down in play) — so, like play-interact, move the
	 * TARGET: its root shifts until the spec's mesh sits `dist` down the crosshair */
	const placeCentre = (spec, dist = 1.6) => {
		const mesh = meshOf(spec);
		const root = rootOf(spec);
		if (!mesh || !root) return false;
		const cam = camera();
		const want = cam.getWorldPosition(new THREE.Vector3()).addScaledVector(cam.getWorldDirection(new THREE.Vector3()), dist);
		const have = new THREE.Box3().setFromObject(mesh).getCenter(new THREE.Vector3());
		const delta = want.sub(have);
		const local = root.parent.worldToLocal(root.getWorldPosition(new THREE.Vector3()).add(delta));
		root.position.copy(local);
		root.updateMatrixWorld(true);
		if (spec.uuid) s.objectsGroup.update((v) => v);
		return true;
	};
	/** ...or move the PLAYER: the rig (the play camera's parent) steps so the camera sits
	 * `dist` back from the mesh along its own view. The target stays put — an object an
	 * effect node pins (a collectible, a football button) is re-seated every frame. */
	const aimRig = (spec, dist = 1.6) => {
		const mesh = meshOf(spec);
		const cam = camera();
		const rig = cam?.parent;
		if (!mesh || !rig || rig === scene()) return false;
		const centre = new THREE.Box3().setFromObject(mesh).getCenter(new THREE.Vector3());
		const want = centre.addScaledVector(cam.getWorldDirection(new THREE.Vector3()), -dist);
		const delta = want.sub(cam.getWorldPosition(new THREE.Vector3()));
		const next = rig.getWorldPosition(new THREE.Vector3()).add(delta);
		rig.position.copy(rig.parent ? rig.parent.worldToLocal(next) : next);
		rig.updateMatrixWorld(true);
		return true;
	};
	const selection = () => read('selectedObjects');
	const playDebug = () => s.playInteract.playInteractDebug?.() ?? null;
	const moduleSelection = () => s.moduleSDK.moduleContentDebug?.().selection?.name ?? null;
	const gizmoObject = () => read('TControls')?.object?.uuid ?? null;
	/** the translate gizmo's X picker, as a screen segment to drag along */
	const gizmoHandle = (axis = 'X') => {
		const controls = read('TControls');
		const helper = controls?.getHelper?.() ?? controls;
		if (!helper) return null;
		let gizmo = null;
		helper.traverse((n) => {
			if (!gizmo && n.picker?.translate) gizmo = n;
		});
		const pickX = gizmo?.picker?.translate?.children?.find((n) => n.name === axis);
		if (!pickX) return null;
		pickX.updateWorldMatrix(true, false);
		const box = new THREE.Box3().setFromObject(pickX);
		const mid = box.getCenter(new THREE.Vector3());
		const origin = controls.object.getWorldPosition(new THREE.Vector3());
		const rect = canvas().getBoundingClientRect();
		const px = (p) => {
			const v = p.clone().project(camera());
			return [rect.left + ((v.x + 1) / 2) * rect.width, rect.top + ((1 - v.y) / 2) * rect.height];
		};
		const a = px(origin);
		const b = px(mid);
		const len = Math.hypot(b[0] - a[0], b[1] - a[1]) || 1;
		return { x: b[0], y: b[1], dx: (b[0] - a[0]) / len, dy: (b[1] - a[1]) / len, onCanvas: document.elementFromPoint(b[0], b[1]) === canvas() };
	};
	const position = (uuid) => objects().getObjectByProperty('uuid', uuid)?.position.toArray() ?? null;
	/** a module reacted: its sends, the replicated notes/params, flow pulses, toasts */
	const reaction = () => {
		const triggers = read('flowTriggers') ?? {};
		let pulses = 0;
		for (const entry of Object.values(triggers)) pulses += (entry?.lastT ?? 0) + (entry?.count ?? 0);
		return {
			sent: (window.__auditSent ?? []).filter((m) => !/look|cursor|presence|ping|heartbeat|camera|clock|avatar|pose|lock|select|^move|nodesync/i.test(m.type + ':' + (m.op ?? ''))).length,
			pulses,
			toasts: (read('toastStore') ?? []).length
		};
	};
	return {
		read,
		objects,
		scene,
		topOf,
		rootOf,
		meshOf,
		frame,
		aim,
		centreAim,
		frameCentre,
		placeCentre,
		aimRig,
		selection,
		playDebug,
		moduleSelection,
		gizmoObject,
		gizmoHandle,
		position,
		reaction
	};
}

async function installLib(page) {
	await page.evaluate(`window.__audit = (${pageLib.toString()})();`);
	// what left this machine: the peer's own send, wrapped (editor-modes' spy)
	await page.evaluate(() => {
		let p;
		window.__stores.peers.subscribe((v) => (p = v))();
		window.__auditSent = [];
		if (!p || p.__auditSpied) return;
		const real = p.send.bind(p);
		p.send = (msg) => {
			window.__auditSent.push({ type: msg?.type, op: msg?.op, moduleId: msg?.moduleId });
			return real(msg);
		};
		p.__auditSpied = true;
	});
}
const A = (page, fn, arg) => page.evaluate(fn, arg);
const lib = (page, call, ...args) => page.evaluate(({ call, args }) => window.__audit[call](...args), { call, args });

async function menu(page, label) {
	const ok = await page.evaluate((label) => {
		let list;
		window.__stores.moduleSDK.moduleMenuItems.subscribe((v) => (list = v))();
		const item = list.find((m) => m.label === label);
		if (!item) return false;
		item.action();
		return true;
	}, label);
	if (!ok) throw new Error('no module menu item "' + label + '"');
}
async function create(page, command) {
	await page.evaluate((c) => window.__stores.commandsHandler.sceneCommand(c), command);
	await page.waitForTimeout(400);
	return page.evaluate(() => {
		let g;
		window.__stores.objectsGroup.subscribe((v) => (g = v))();
		return g.children[g.children.length - 1]?.uuid ?? null;
	});
}
/** place a replicated object (the core suites' write: position + objectsGroup.update) */
function place(page, uuid, pos) {
	return page.evaluate(
		({ uuid, pos }) => {
			let g;
			window.__stores.objectsGroup.subscribe((v) => (g = v))();
			const o = g.getObjectByProperty('uuid', uuid);
			o.position.set(pos[0], pos[1], pos[2]);
			o.updateMatrixWorld(true);
			window.__stores.objectsGroup.update((v) => v);
		},
		{ uuid, pos }
	);
}
async function waitFor(page, fn, arg, timeout = 15000) {
	const start = Date.now();
	let last;
	while (Date.now() - start < timeout) {
		last = await page.evaluate(fn, arg);
		if (last) return last;
		await page.waitForTimeout(300);
	}
	return last;
}
/** uuids of the top-level objects of the module's audio devices, by kind prefix */
function devicesOf(page, prefix) {
	return page.evaluate((prefix) => {
		const out = [];
		for (const d of window.__stores.audioDevices.devicesDebug().built)
			if (d.kind.startsWith(prefix)) {
				let g;
				window.__stores.objectsGroup.subscribe((v) => (g = v))();
				const o = g.getObjectByProperty('uuid', d.uuid);
				if (o && o.parent === g) out.push({ uuid: d.uuid, label: d.kind.slice(prefix.length) });
			}
		return out;
	}, prefix);
}
async function loadTemplate(page, slug) {
	const file = path.join(SCENES_DIR, 'games', slug, 'scene.tpscene');
	if (!fs.existsSync(file)) throw new Error('template not found: ' + file);
	const bytes = fs.readFileSync(file);
	await page.evaluate(async (arr) => {
		const s = window.__stores;
		await s.sessions.applySession(await s.sessions.readSessionZip(new Uint8Array(arr).buffer), { backup: false });
	}, Array.from(bytes));
	await page.waitForTimeout(2500);
}
const byName = (page, name) =>
	page.evaluate((n) => {
		let g;
		window.__stores.objectsGroup.subscribe((v) => (g = v))();
		return g.children.find((c) => c.name === n)?.uuid ?? null;
	}, name);

